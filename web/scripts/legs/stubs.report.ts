// D4 (TRP-GL review): every dashed straight-line stub (`leg:<day>:<n>:a` / `:b`) that routeSpec draws with the REAL stored legs, over every
// picked day and every variant of the public trips that have a legs file, with its length. One-off evidence, not a gate: it writes
// a dated stub-report file in docs/v2/build/public-site/. Run: pnpm exec vitest run --config scripts/legs/vitest.stubs.config.mts
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { it } from 'vitest';
import { haversineM } from '@travel/core/geo/distance.ts';
import { scheduleDay } from '@travel/core/schedule/schedule.ts';
import { DEFAULT_PROFILE, type Profile } from '@travel/core/schedule/types.ts';
import { buildTripExport } from '@/lib/export/build.server';
import { getPlace, getTrip } from '@/lib/public';
import { getStore } from '@/lib/server/store';
import { buildTripPageModel } from '@/components/trips/model';
import { legGeometry } from '@/components/trips/legGeometry';
import { dayMapOf, pointLookup } from '@/components/trips/mapPins';
import { routeSpec, STUB_GAP_M } from '@/components/trips/routeSpec';

const SLUGS = ['canadian-rockies-2029', 'dolomites-2027'];
const PROFILES: Record<string, Profile> = {
  adults: { ...DEFAULT_PROFILE, party: 'adults', youngest: null },
  'family-6': { ...DEFAULT_PROFILE, party: 'family', youngest: 6 },
  'family-4': { ...DEFAULT_PROFILE, party: 'family', youngest: 4 },
};
interface Row { trip: string; day: number; variant: string; profile: string; id: string; gapM: number }

it('lists every straight-line stub with its length', async () => {
  const rows: Row[] = [];
  let spec = 0;
  for (const slug of SLUGS) {
    const trip = getTrip(slug)!;
    const r = await getStore().tripLegs(slug);
    if (!r.ok || 'moved' in r.data) throw new Error(`no legs for ${slug}`);
    const legs = r.data;
    const page = buildTripPageModel(trip, (s) => { const p = getPlace(s); return p ? { point: p.point ? { lat: p.point.lat, lon: p.point.lon } : null, photo: p.photo } : null; }, []);
    const pointOf = pointLookup(page.route);
    const model = buildTripExport(trip);
    const by = new Map(model.stops.flatMap((x) => (x.placeSlug ? [[x.id, x.placeSlug] as const] : [])));
    const slugOf = (k: string) => by.get(k) ?? null;
    const inputs = trip.days.map((d) => d.scheduleInput!);
    for (const [pname, profile] of [['default', trip.schedule!.defaultProfile] as const, ...Object.entries(PROFILES)]) {
      for (const input of inputs) {
        for (const v of input.variants.length ? input.variants.map((x) => x.key) : [null]) {
          // the other days stay on their profile-chosen variant; only the picked day takes this variant
          const timelines = inputs.map((i) => scheduleDay(i, profile, { variant: i.day === input.day ? v : null }));
          const models = timelines.map((t) => dayMapOf(t, pointOf));
          const geometry = legGeometry(legs.legs, models, page.route.bases, slugOf, pointOf);
          const s = routeSpec({ bases: page.route.bases, models, picked: input.day, geometry });
          spec++;
          const g = (a: { lng: number; lat: number }, b: { lng: number; lat: number }) => haversineM({ lat: a.lat, lon: a.lng }, { lat: b.lat, lon: b.lng });
          for (const l of s.lines) if (/:[ab]$/.test(l.id)) rows.push({ trip: slug, day: input.day, variant: v ?? 'main', profile: pname, id: l.id, gapM: g(l.coords[0]!, l.coords[l.coords.length - 1]!) });
        }
      }
    }
  }
  // the same stub appears under several profiles: keep the longest row per (trip, day, variant, id)
  const best = new Map<string, Row>();
  for (const x of rows) { const k = `${x.trip}|${x.day}|${x.variant}|${x.id}`; const o = best.get(k); if (!o || x.gapM > o.gapM) best.set(k, x); }
  const list = [...best.values()].sort((a, b) => b.gapM - a.gapM);
  const big = list.filter((x) => x.gapM >= 1000);
  const fmt = (m: number) => (m >= 1000 ? `${(m / 1000).toFixed(2)} km` : `${Math.round(m)} m`);
  const md = [
    '# Straight-line stub report, 26 Oct 2026 (D4)',
    '',
    `Generated by \`web/scripts/legs/stubs.report.ts\` (one-off; rerun with \`pnpm exec vitest run --config scripts/legs/vitest.stubs.config.mts\` from \`web/\`). It runs \`routeSpec\` with the real stored legs over every picked day and every variant of the public trips that have a legs file (${SLUGS.join(', ')}), under the default profile and the adults, family-6 and family-4 profiles: ${spec} specs. A stub is the dashed straight line (\`leg:<day>:<n>:a\` or \`:b\`) joining a pin to the end of its routed line when the two are more than ${STUB_GAP_M} m apart. Trips with no legs file draw no routed line and so no stub.`,
    '',
    big.length ? `**D4 does not close on this list: ${big.length} stub(s) are 1 km or more. Longest: ${big[0]!.trip} day ${big[0]!.day} (${big[0]!.variant}) \`${big[0]!.id}\`, ${fmt(big[0]!.gapM)}.** It needs real-key shots at 1440 and 390, light and dark (review D4, step 3).` : `**D4 closes: no stub is 1 km or more** (${list.length ? `the longest is ${fmt(list[0]!.gapM)}` : 'there are no stubs at all'}).`,
    '',
    `${list.length} stubs, longest first.`,
    '',
    '| Trip | Day | Variant | Line id | Gap |',
    '|---|---|---|---|---|',
    ...list.map((x) => `| ${x.trip} | ${x.day} | ${x.variant} | \`${x.id}\` | ${fmt(x.gapM)} |`),
    '',
  ].join('\n');
  console.log(md);
  writeFileSync(path.resolve(process.cwd(), '..', 'docs', 'v2', 'build', 'public-site', 'stub-report-2026-10-26.md'), md);
});
