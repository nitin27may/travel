import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { createPublicData } from '@/lib/public';
import { travelRoot } from '@/lib/data/root';

// docs/v2/research/trip-tag-conflicts.md: where the scheduler's Kids from N and Hike effort differ from the plan's own typed values, what
// decides each, and whether a gap is involved. Generated: `pnpm --dir web tag-conflicts` rewrites it; this test fails when it is stale.
const FILE = path.join(travelRoot(), 'docs', 'v2', 'research', 'trip-tag-conflicts.md');
const TAG = { kidsFrom: 'Kids from N', hike: 'Hike effort' } as const;
const cell = (v: string | number | null) => (v === null ? 'none' : String(v)).replace(/\|/g, '/');

export function report(): string {
  const rows = createPublicData().internals.tagReport;
  const lines = [
    '# Trip tags: scheduler against the plan\'s typed values',
    '',
    'Generated by `pnpm --dir web tag-conflicts` from the public adapter. Do not edit.',
    '',
    'A computed value is published only when it rests on known data: a gap is never a fit (a day whose chosen variant holds an item with no age and no distance on record is unknown, not "no limit"). Where the scheduler cannot say, the card keeps the plan\'s own typed value ("our plan"). Hike effort counts only trails with a known effort, in the variant the trip\'s default family profile picks; an adults-only variant never sets it.',
    '',
    '| Trip | Tag | Typed | Computed | Shown | Decided by | Gap |',
    '|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.trip} | ${TAG[r.field]} | ${cell(r.typed)} | ${cell(r.computed)} | ${cell(r.shown)} | ${cell(r.decider)} | ${cell(r.gap)} |`),
    '',
    `Differences (computed and typed both set, not equal): ${rows.filter((r) => r.computed !== null && r.computed !== r.typed).length} of ${rows.length}.`,
    '',
  ];
  return lines.join('\n');
}

describe('trip tag conflicts report', () => {
  it('is the committed file', () => {
    const text = report();
    if (process.env.WRITE_TAG_REPORT === '1') writeFileSync(FILE, text);
    expect(existsSync(FILE)).toBe(true);
    expect(readFileSync(FILE, 'utf8')).toBe(text);
  });
  it('never shows a computed Kids-from of 0 as a number: 0 means all ages and only stands on known data', () => {
    for (const r of createPublicData().internals.tagReport.filter((x) => x.field === 'kidsFrom' && x.computed === 0)) expect(r.gap, r.trip).toBe('none');
  });
});
