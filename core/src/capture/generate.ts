// The generator (capture contract 5.1): types.json + the property registry -> the files readers use.
//
//   data/schema/capture/<domain>.json   every node resolved (a node identical to its parent says `inherits`)
//   data/schema/capture/contract.json   the section map, the property table and the facets, for the public adapter (P9)
//   data/schema/suitability-applicability.json   unchanged shape, now generated
//   docs/v2/research/capture/<domain>.md        the checklist a person reads
//
// Deterministic: the same inputs always give the same bytes, so `build --check` can compare text.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import * as E from "../schema/enums.ts";
import { PROPERTIES, PROPERTY_BY_KEY } from "../schema/capture/properties.ts";
import type { TypesFile } from "../schema/capture/typesFile.ts";
import { APPLICABILITY_PATHS } from "../suitability/paths.ts";
import { resolveNode } from "./resolve.ts";
import type { ResolvedNode } from "./resolve.ts";
import { loadTypes, treeOf } from "./tree.ts";

export const GENERATED_DIR = "data/schema/capture";
export const APPLICABILITY_PATH = "data/schema/suitability-applicability.json";
export const DOCS_DIR = "docs/v2/research/capture";
const HEADER = "Generated by `node core/bin/capture.ts build` from data/vocab/types.json and core/src/schema/capture/properties.ts. Do not edit by hand.";

export interface Output { path: string; text: string }

type Obj = Record<string, unknown>;
/** The contract part of a resolved node: what two nodes must share to be the same contract. */
function contractOf(n: ResolvedNode): Obj {
  const layers: Obj = {};
  for (const [l, rl] of Object.entries(n.layers)) {
    const base: Obj = {};
    for (const [k, m] of Object.entries(rl!.base)) base[k] = m;
    layers[l] = { offer_class: rl!.offer_class, carries_suitability: rl!.carries_suitability, base };
  }
  return { records: n.records, profile: n.profile, operated: n.operated, operated_default: n.operated_default, ext: n.ext, suitability: n.suitability, effort: n.effort, relevance_class: n.relevance_class, layers, links: n.links, sources: n.sources, display: n.display };
}

/** draft, usable and complete as lists of property keys, per layer (the D/U/C checks of the kind profiles, generated). */
export function levelsOf(n: ResolvedNode, layer: keyof ResolvedNode["layers"]): { draft: string[]; usable: string[]; complete: string[] } {
  const rl = n.layers[layer];
  if (!rl) return { draft: [], usable: [], complete: [] };
  const draft: string[] = [];
  const usable: string[] = [];
  const complete: string[] = [];
  for (const [k, m] of Object.entries(rl.base)) {
    const def = PROPERTY_BY_KEY.get(k);
    if (m === "R") {
      usable.push(k);
      if (def?.group === "identity" || k === "type" || k === "name") draft.push(k);
    } else if (m === "R?") usable.push(`${k}?`);
    else if (m === "A") complete.push(k);
  }
  if (rl.carries_suitability) {
    for (const [k, m] of Object.entries(n.suitability)) {
      if (m === "R") usable.push(k);
      else if (m === "A") complete.push(k);
      else usable.push(`${k}?operated`);
    }
  }
  return { draft: draft.sort(), usable: usable.sort(), complete: complete.sort() };
}

function nodeEntry(n: ResolvedNode, parent: ResolvedNode | null): Obj {
  const head: Obj = { label: n.label, level: n.level };
  if (n.aliases.length) head.aliases = n.aliases;
  if (parent && JSON.stringify(contractOf(n)) === JSON.stringify(contractOf(parent))) return { ...head, inherits: parent.id };
  const layers: Obj = {};
  for (const [l, rl] of Object.entries(n.layers)) {
    layers[l] = { ...(rl!.offer_class ? { offer_class: rl!.offer_class } : {}), carries_suitability: rl!.carries_suitability, base: rl!.base, levels: levelsOf(n, l as never) };
  }
  return {
    ...head,
    records: n.records,
    profile: n.profile,
    operated: n.operated,
    ...(n.operated_default !== null ? { operated_default: n.operated_default } : {}),
    ext: n.ext,
    suitability: n.suitability,
    effort: n.effort.scales,
    relevance_class: n.relevance_class,
    links: n.links,
    sources: n.sources,
    display: n.display,
    layers,
  };
}

const oneLine = (x: unknown): string => JSON.stringify(x);

function domainFile(file: TypesFile, domain: string): Output {
  const tree = treeOf(file);
  const lines: string[] = [];
  const ids = file.nodes.filter((n) => n.id === domain || n.id.startsWith(`${domain}.`));
  ids.forEach((n, i) => {
    const r = resolveNode(n.id, file)!;
    const parent = n.parent ? resolveNode(n.parent, file) : null;
    lines.push(`    ${oneLine(n.id)}: ${oneLine(nodeEntry(r, parent))}${i < ids.length - 1 ? "," : ""}`);
  });
  void tree;
  const text = [
    "{",
    '  "schema": "capture-contract/1",',
    `  "note": ${oneLine(HEADER)},`,
    `  "domain": ${oneLine(domain)},`,
    '  "nodes": {',
    ...lines,
    "  }",
    "}",
    "",
  ].join("\n");
  return { path: `${GENERATED_DIR}/${domain}.json`, text };
}

function sectionTable(): Obj[] {
  return E.CAP_SECTION.map((id, i) => ({ n: i + 1, id }));
}

function contractFile(file: TypesFile): Output {
  const props: Obj = {};
  for (const p of PROPERTIES) {
    props[p.key] = { label: p.label, group: p.group, value: p.value, ...(p.unit ? { unit: p.unit } : {}), gap: p.gap, section: p.section, display: p.display, ...(p.trigger ? { trigger: p.trigger } : {}), home: p.home, ...(p.layers ? { layers: p.layers } : {}) };
  }
  const facets: Obj[] = PROPERTIES.filter((p) => p.filter).map((p) => ({ property: p.key, scopes: p.filter!.scopes, control: p.filter!.control, label: p.filter!.label, ...(p.filter!.band ? { band: p.filter!.band } : {}) }));
  const lines = [
    "{",
    '  "schema": "capture-ui-contract/1",',
    `  "note": ${oneLine(HEADER)},`,
    `  "updated": ${oneLine(file.updated)},`,
    `  "sections": ${oneLine(sectionTable())},`,
    '  "bands": {"time_band": ["<1h", "1-2h", "2-4h", "half-day", "full-day", "multi-day"], "price_band": ["free", "$", "$$", "$$$"], "booking": ["none", "recommended", "required"]},',
    '  "properties": {',
    ...Object.entries(props).map(([k, v], i, a) => `    ${oneLine(k)}: ${oneLine(v)}${i < a.length - 1 ? "," : ""}`),
    "  },",
    '  "facets": [',
    ...facets.map((f, i) => `    ${oneLine(f)}${i < facets.length - 1 ? "," : ""}`),
    "  ]",
    "}",
    "",
  ];
  return { path: `${GENERATED_DIR}/contract.json`, text: lines.join("\n") };
}

/** data/schema/suitability-applicability.json in the shape suitability.ts has always read. */
export function applicabilityFile(file: TypesFile): Output {
  const profiles: Record<string, { match: { kind: string; subkind: string }[]; operated: string; ext: string | null; fields: Record<string, string> }> = {};
  for (const [name, p] of Object.entries(file.profiles)) {
    const fields: Record<string, string> = {};
    for (const path of APPLICABILITY_PATHS) fields[path] = p.fields[path] ?? "N";
    profiles[name] = { match: [], operated: p.operated, ext: p.ext, fields };
  }
  for (const n of file.nodes) {
    const r = resolveNode(n.id, file)!;
    if (!r.profile || !n.legacy || !profiles[r.profile]) continue;
    for (const l of n.legacy) profiles[r.profile]!.match.push({ kind: l.kind, subkind: l.subkind });
  }
  const f_labels: Record<string, string> = {};
  for (const path of APPLICABILITY_PATHS) if (!path.startsWith("ext.")) f_labels[path] = PROPERTY_BY_KEY.get(path)!.label;
  const lines = [
    "{",
    '  "schema_version": 1,',
    `  "updated": ${oneLine(file.updated)},`,
    `  "note": ${oneLine("Which suitability field applies to which kind. R = required for Usable, A = applicable (counts for Complete), N = never asked, shown or counted, op = R when the record is operated, else N. " + HEADER + " Edit the `profiles` block of data/vocab/types.json.")},`,
    `  "f_labels": ${oneLine(f_labels)},`,
    '  "profiles": {',
    ...Object.entries(profiles).map(([name, p], i, a) => {
      const body = [
        `      "match": ${oneLine(p.match)}`,
        `      "operated": ${oneLine(p.operated)}`,
        `      "ext": ${oneLine(p.ext)}`,
        `      "fields": ${oneLine(p.fields)}`,
      ];
      return `    ${oneLine(name)}: {\n${body.join(",\n")}\n    }${i < a.length - 1 ? "," : ""}`;
    }),
    "  }",
    "}",
    "",
  ];
  return { path: APPLICABILITY_PATH, text: lines.join("\n") };
}

function docFile(file: TypesFile, domain: string): Output {
  const out: string[] = [];
  const dom = file.nodes.find((n) => n.id === domain)!;
  out.push(`# Capture checklist: ${dom.label}`, "", `<!-- ${HEADER} -->`, "");
  out.push("R is required for Usable, R? is required when its condition holds, A is applicable (counts for Complete). Properties not listed are never asked. Suitability paths are listed under their profile; the full list for a type is `node core/bin/capture.ts fields --type <id>`.", "");
  for (const n of file.nodes.filter((x) => x.id === domain || x.id.startsWith(`${domain}.`))) {
    if (n.level === "domain" && !n.category) continue;
    const r = resolveNode(n.id, file)!;
    const parent = n.parent ? resolveNode(n.parent, file) : null;
    if (n.level === "subtype" || (n.level === "type" && parent && JSON.stringify(contractOf(r)) === JSON.stringify(contractOf(parent)))) continue; // identical to its parent
    const depth = n.level === "category" || n.category ? "##" : "###";
    out.push(`${depth} ${n.label} (\`${n.id}\`)`, "");
    out.push(`Records: ${r.records.join(", ")}. ${r.profile ? `Suitability profile \`${r.profile}\` (${r.operated}${r.ext ? `, extension ${r.ext}` : ""}).` : "No suitability profile."} Effort: ${r.effort.scales.length ? r.effort.scales.join(", ") : "none, time is shown"}. Sources, in order: ${r.sources.join(" ") || "none"}.`, "");
    for (const l of r.records) {
      const rl = r.layers[l]!;
      const lv = levelsOf(r, l);
      const R = Object.entries(rl.base).filter(([, m]) => m === "R").map(([k]) => k);
      const Rq = Object.entries(rl.base).filter(([, m]) => m === "R?").map(([k]) => `${k} (${PROPERTY_BY_KEY.get(k)?.trigger ?? "conditional"})`);
      const A = Object.entries(rl.base).filter(([, m]) => m === "A").map(([k]) => k);
      out.push(`**${l}${rl.offer_class ? ` (${rl.offer_class})` : ""}**: R ${R.join(", ") || "none"}; R? ${Rq.join(", ") || "none"}; A ${A.join(", ") || "none"}.`, "");
      void lv;
    }
    const sr = Object.entries(r.suitability).filter(([, m]) => m === "R").map(([k]) => k);
    const sa = Object.entries(r.suitability).filter(([, m]) => m === "A").map(([k]) => k);
    const so = Object.entries(r.suitability).filter(([, m]) => m === "op").map(([k]) => k);
    if (r.profile) out.push(`Suitability: R ${sr.join(", ") || "none"}; R when operated ${so.join(", ") || "none"}; A ${sa.join(", ") || "none"}.`, "");
    out.push(`Links: official; R? ${r.links["R?"].join(", ") || "none"}; A ${r.links.A.join(", ") || "none"}.`, "");
  }
  return { path: `${DOCS_DIR}/${domain}.md`, text: out.join("\n").replace(/\n{3,}/g, "\n\n") };
}

/** Every generated file for a types file, in a stable order. */
export function generate(file: TypesFile = loadTypes()): Output[] {
  const domains = file.nodes.filter((n) => n.level === "domain").map((n) => n.id);
  const out: Output[] = [];
  for (const d of domains) out.push(domainFile(file, d));
  out.push(contractFile(file));
  out.push(applicabilityFile(file));
  for (const d of domains) out.push(docFile(file, d));
  return out;
}

export interface Drift { path: string; reason: "missing" | "differs" | "stale" }

/** Compares the generated files with disk. `stale` is a file in the generated folders that no longer has a source. */
export function checkDrift(root: string, file: TypesFile = loadTypes(root)): Drift[] {
  const outs = generate(file);
  const drift: Drift[] = [];
  for (const o of outs) {
    const p = join(root, o.path);
    if (!existsSync(p)) drift.push({ path: o.path, reason: "missing" });
    else if (readFileSync(p, "utf8") !== o.text) drift.push({ path: o.path, reason: "differs" });
  }
  const known = new Set(outs.map((o) => o.path));
  for (const dir of [GENERATED_DIR, DOCS_DIR]) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const n of readdirSync(abs)) {
      const rel = `${dir}/${n}`;
      if ((n.endsWith(".json") || n.endsWith(".md")) && !known.has(rel)) drift.push({ path: rel, reason: "stale" });
    }
  }
  return drift;
}

export function writeAll(root: string, file: TypesFile = loadTypes(root)): { written: string[]; removed: string[] } {
  const outs = generate(file);
  const written: string[] = [];
  for (const o of outs) {
    const p = join(root, o.path);
    mkdirSync(dirname(p), { recursive: true });
    if (!existsSync(p) || readFileSync(p, "utf8") !== o.text) {
      writeFileSync(p, o.text);
      written.push(o.path);
    }
  }
  const removed: string[] = [];
  for (const d of checkDrift(root, file)) {
    if (d.reason === "stale") {
      rmSync(join(root, d.path));
      removed.push(d.path);
    }
  }
  return { written, removed };
}
