// Builds the golden set core/test/fixtures/drive/golden-legs.json (driving-time-model.md 5.7) from the stored ORS legs and the research
// runs of DRIVE_INPUTS (Node only: it reads files; offline). Each end gets its country and subdivision from the nearest town of the
// towns layer (GeoNames) and its area from the derive-area point rule (core/src/capture/deriveArea.ts, the same labels and radius),
// so the terrain of a pair follows areas.json. The area lookup loads the capture world: slow, so only `pairs --write | --check` runs it;
// the calibration reads the fixture.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { loadAreaInput, pointDecision, subjectLabels } from "../capture/deriveArea.ts";
import { DRIVE_CALIBRATION, DRIVE_INPUTS } from "../config/drive.ts";
import { nearestTown } from "../derive/near.ts";
import { readTownsFiles } from "../derive/townsData.ts";
import { dedupePairs, legsFilePairs, runFilePairs, type RawPair } from "./pairs.ts";
import { DRIVE_SCHEMA_IDS, type GoldenFile, type GoldenPair } from "./schema.ts";
import { GOLDEN_PATH } from "./calibrate.ts";

/** The routed pairs of every input, deduplicated, in input order (legs files by name, then the runs). No area lookup. */
export function collectRawPairs(root: string): { pairs: RawPair[]; attribution: string } {
  const dir = join(root, DRIVE_INPUTS.legsDir);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json") && !f.endsWith(".unrouted.json")).sort() : [];
  const all: RawPair[] = [];
  let attribution = "";
  for (const f of files) {
    const rel = `${DRIVE_INPUTS.legsDir}/${f}`;
    const doc = JSON.parse(readFileSync(join(root, rel), "utf8")) as { attribution?: string };
    attribution ||= doc.attribution ?? "";
    all.push(...legsFilePairs(rel, doc));
  }
  for (const rel of DRIVE_INPUTS.runs) {
    if (!existsSync(join(root, rel))) throw new Error(`${rel} is missing (a calibration input in core/src/config/drive.ts)`);
    all.push(...runFilePairs(rel, JSON.parse(readFileSync(join(root, rel), "utf8"))));
  }
  return { pairs: dedupePairs(all), attribution };
}

/** Lines that say how the fixture differs from the inputs today (a refreshed legs file, a new run); empty when it matches. */
export function goldenDrift(golden: GoldenFile, raw: readonly RawPair[]): string[] {
  const out: string[] = [];
  if (golden.pairs.length !== raw.length) out.push(`the inputs give ${raw.length} pairs, the golden set holds ${golden.pairs.length}`);
  const n = Math.min(golden.pairs.length, raw.length);
  for (let i = 0; i < n && out.length < 10; i++) {
    const g = golden.pairs[i]!;
    const r = raw[i]!;
    if (g.id !== r.id || g.km !== r.km || g.minutes !== r.minutes || g.a.lat !== r.a.lat || g.a.lon !== r.a.lon || g.b.lat !== r.b.lat || g.b.lon !== r.b.lon) {
      out.push(`pair ${i} differs: golden ${g.id} (${g.km} km, ${g.minutes} min), inputs ${r.id} (${r.km} km, ${r.minutes} min)`);
    }
  }
  return out;
}

/** The full golden document (slow: loads the towns layer and the capture world for the area labels). */
export function buildGolden(root: string): GoldenFile {
  const { pairs, attribution } = collectRawPairs(root);
  const towns = readTownsFiles(root).rows;
  const townById = new Map(towns.map((t) => [t.id, t]));
  const { input } = loadAreaInput(root);
  const labels = [...subjectLabels(input.subjects), ...input.storeLabels];
  const memo = new Map<string, GoldenPair["a"]>();
  const place = (p: { lat: number; lon: number }): GoldenPair["a"] => {
    const k = `${p.lat},${p.lon}`;
    const hit = memo.get(k);
    if (hit) return hit;
    const hitTown = nearestTown(p, towns, DRIVE_CALIBRATION.townLookupRadius, 0);
    const t = hitTown ? townById.get(hitTown.town.id) ?? null : null;
    const dec = pointDecision({ ref: "drive-golden", trip: "", point: { ...p, approx: false }, town: null, parents: [], authored: null }, labels, input);
    const areaCc = dec.area ? dec.area.slice(0, 2) : null;
    const cc = t ? t.cc.toUpperCase() : areaCc;
    const admin1 = t?.admin1.toUpperCase() ?? null;
    const area = dec.area && dec.area.startsWith(`${cc}/`) ? dec.area : null;
    // an area id whose region is an ISO 3166-2 suffix (`CA/AB/...`) names the subdivision more reliably than the nearest town
    const areaSub = area?.split("/")[1] ?? "";
    const sub = /^[A-Z0-9]{1,3}$/.test(areaSub) ? areaSub : admin1 && admin1 !== "00" ? admin1 : null;
    const end = { lat: p.lat, lon: p.lon, cc, sub, area };
    memo.set(k, end);
    return end;
  };
  const counts = new Map<string, number>();
  for (const p of pairs) counts.set(p.source, (counts.get(p.source) ?? 0) + 1);
  return {
    schema: DRIVE_SCHEMA_IDS.golden,
    generated: `Generated by node core/bin/drive-calibrate.ts pairs --write from the stored ORS legs and the research runs of core/src/config/drive.ts. Do not edit. Path: ${GOLDEN_PATH}`,
    engine: "ors",
    profile: "driving-car",
    attribution,
    sources: [...counts.entries()].map(([file, n]) => ({ file, pairs: n })),
    pairs: pairs.map((p) => ({ id: p.id, source: p.source, a: place(p.a), b: place(p.b), straightKm: p.straightKm, km: p.km, minutes: p.minutes })),
  };
}
