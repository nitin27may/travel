// The data files of the drive model (driving-time-model.md 5.1 to 5.5 and 5.7; DT-C): Zod schemas for
//   data/reference/drive/countries.json          drive-profile/1      authored: legal limits, terrain default, winter, borders, ferries
//   data/reference/drive/areas.json              drive-areas/1        authored: terrain class per area id of the locations store
//   data/reference/drive/crossings.json          drive-crossings/1    authored: "ferry needed" and "closed in season" area pairs
//   data/reference/drive/segments.json           drive-segments/1     authored: closed, 4x4-only, slow or fixed-time stretches
//   data/reference/drive/generated/calibration.json  drive-calibration/1  generated by core/bin/drive-calibrate.ts; never edited
//   core/test/fixtures/drive/golden-legs.json    drive-golden/1       generated: the routed pairs calibration and the golden tests read
// The rules a schema cannot hold (area ids exist in the registry, one row per cc and sub) are check.ts.
import { z } from "zod";
import { DRIVE_TERRAINS } from "../config/drive.ts";
import { DRIVE_FLAGS } from "./types.ts";

export const DRIVE_SCHEMA_IDS = {
  profile: "drive-profile/1",
  areas: "drive-areas/1",
  crossings: "drive-crossings/1",
  segments: "drive-segments/1",
  calibration: "drive-calibration/1",
  golden: "drive-golden/1",
} as const;

const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "a date YYYY-MM-DD");
const kmh = z.number().int().min(5).max(160);
const month = z.number().int().min(1).max(12);
const months = z.array(month).min(1).max(12).refine((m) => new Set(m).size === m.length, "months repeat");
const cc = z.string().regex(/^[A-Z]{2}$/, "ISO 3166-1 alpha-2, upper case");
const sub = z.string().regex(/^[A-Z0-9]{1,3}$/, "the ISO 3166-2 suffix, upper case");
const areaId = z.string().regex(/^[A-Z]{2}\/[A-Za-z0-9-]+\/[a-z0-9-]+$/, "an area id of the locations store (CC/region/slug)");
const url = z.url({ protocol: /^https$/ });

/** Where a value was read: a URL, its title and the read date. */
export const driveSource = z.strictObject({ url, title: z.string().min(3).max(200), read: isoDate });

export const driveTerrain = z.enum(DRIVE_TERRAINS);

/** Car limits in km/h by road class; null where the class does not exist or has no general limit (posted only). */
export const legalSpeeds = z.strictObject({
  urban: kmh.nullable(),
  rural: kmh.nullable(),
  expressway: kmh.nullable(),
  motorway: kmh.nullable(),
  unpaved: kmh.nullable(),
});

export const winterRule = z.strictObject({
  months,
  /** speed x factor in those months */
  factor: z.number().min(0.5).max(1),
  /** `prior` until a measured value replaces it */
  basis: z.enum(["prior", "measured", "official"]),
  note: z.string().max(300).optional(),
});

export const profileRow = z.strictObject({
  cc,
  sub: sub.nullable(),
  name: z.string().min(2).max(80),
  side: z.enum(["right", "left"]),
  legal: legalSpeeds,
  legalSource: driveSource,
  /** the terrain a point outside every listed area takes */
  terrain: driveTerrain,
  terrainBasis: z.enum(["prior", "measured"]),
  rain: z.strictObject({ motorway: kmh.optional(), expressway: kmh.optional() }).nullable(),
  winter: winterRule.nullable(),
  /** minutes to cross into this country from each neighbour (ISO alpha-2); Schengen neighbours 0 */
  borderDefaultMin: z.record(cc, z.number().int().min(0).max(240)),
  ferryCheckinMin: z.number().int().min(0).max(240).nullable(),
  version: z.number().int().min(1),
  read: isoDate,
  note: z.string().max(400).optional(),
});

export const profileFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.profile),
  about: z.string().min(10),
  licence: z.string().min(10),
  rows: z.array(profileRow).min(1),
});

export const areaRow = z.strictObject({
  area: areaId,
  terrain: driveTerrain,
  basis: z.enum(["prior", "measured"]),
  /** the share (0 to 1) of road km on unpaved roads */
  unpavedShare: z.number().min(0).max(1),
  /** a winter factor for this area that overrides the country's (mountain areas 0.80, spec 4.4) */
  winterFactor: z.number().min(0.5).max(1).nullable(),
  note: z.string().min(3).max(300),
});

export const areasFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.areas),
  about: z.string().min(10),
  rows: z.array(areaRow),
});

const ref = z.string().min(3).max(200).regex(/^[a-z]+\/[a-z0-9/#._-]+$/, "a public ref (place/<slug>)");

export const crossingRow = z
  .strictObject({
    id: z.string().regex(/^[a-z0-9-]+$/),
    from: areaId,
    to: areaId,
    kind: z.enum(["ferry", "closed-season"]),
    /** the ferry route or pass record */
    via: ref.nullable(),
    symmetric: z.boolean(),
    /** ferry: sailing minutes; closed-season: the extra minutes of the way round */
    minutes: z.number().int().min(0).max(2880),
    checkinMin: z.number().int().min(0).max(240).nullable(),
    /** ferry: minutes between sailings by month ("1" to "12"); half is added as the expected wait */
    headwayMin: z.record(z.string().regex(/^(?:[1-9]|1[0-2])$/), z.number().int().min(0).max(10080)).nullable(),
    /** closed-season: the months the direct way is closed */
    months: months.nullable(),
    source: driveSource,
  })
  .refine((r) => r.kind !== "closed-season" || r.months !== null, { message: "a closed-season crossing needs its months" });

export const crossingsFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.crossings),
  about: z.string().min(10),
  rows: z.array(crossingRow),
});

export const segmentRow = z
  .strictObject({
    id: z.string().regex(/^[a-z0-9-]+$/),
    /** public refs of the points the stretch serves (a leg to or from one of them is affected) */
    refs: z.array(ref).min(1).optional(),
    /** an encoded polyline (precision 5) of the stretch, for the routed layers */
    line: z.string().min(2).optional(),
    rule: z.enum(["closed", "4x4", "slow", "fixed"]),
    minutes: z.number().int().min(1).max(2880).optional(),
    factor: z.number().min(1).max(5).optional(),
    /** the months the rule holds; absent: all year */
    months: months.optional(),
    note: z.string().min(3).max(300),
    /** the shuttle or the operator page shown on a `none` leg */
    link: url.optional(),
    source: driveSource,
  })
  .refine((r) => r.refs !== undefined || r.line !== undefined, { message: "a segment needs refs or a line" })
  .refine((r) => r.rule !== "fixed" || r.minutes !== undefined, { message: "a fixed segment needs minutes" })
  .refine((r) => r.rule !== "slow" || r.factor !== undefined, { message: "a slow segment needs a factor" });

export const segmentsFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.segments),
  about: z.string().min(10),
  rows: z.array(segmentRow),
});

const ratio = z.number().min(0).max(20);

/** The error of one model over one slice of the golden set. */
export const errorStats = z.strictObject({
  n: z.number().int().min(0),
  meanError: ratio,
  medianBias: z.number(),
  p90Error: ratio,
  within20: ratio,
});

export const calibrationCell = z.strictObject({
  /** `CA|mountain|30-60` */
  cell: z.string(),
  cc,
  terrain: driveTerrain,
  band: z.string(),
  n: z.number().int().min(1),
  /** routed km / prior road km: median, and the shrunk factor the model applies */
  detour: z.strictObject({ median: ratio, factor: ratio }),
  /** routed speed / prior speed: median, and the shrunk factor */
  speed: z.strictObject({ median: ratio, factor: ratio }),
  /** routed minutes / calibrated minutes, p10 and p90, shrunk toward the prior range */
  range: z.tuple([ratio, ratio]),
});

export const calibrationFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.calibration),
  generated: z.string().min(10),
  inputs: z.strictObject({ golden: z.string(), sha256: z.string().regex(/^[0-9a-f]{64}$/), pairs: z.number().int().min(0) }),
  shrinkPairs: z.number().int().min(1),
  cells: z.array(calibrationCell),
  /** the golden set's error: today's naive rule, the uncalibrated prior, the calibrated model, and leave-one-out */
  summary: z.strictObject({
    naive: z.record(z.string(), errorStats),
    prior: z.record(z.string(), errorStats),
    calibrated: z.record(z.string(), errorStats),
    leaveOneOut: z.record(z.string(), errorStats),
    bands: z.record(z.string(), errorStats),
  }),
});

export const goldenEnd = z.strictObject({
  lat: z.number().min(-90).max(90),
  lon: z.number().min(-180).max(180),
  cc: cc.nullable(),
  sub: sub.nullable(),
  area: areaId.nullable(),
});

export const goldenPair = z.strictObject({
  id: z.string().min(3),
  source: z.string().min(3),
  a: goldenEnd,
  b: goldenEnd,
  straightKm: z.number().min(0),
  km: z.number().min(0),
  minutes: z.number().min(0),
});

export const goldenFile = z.strictObject({
  schema: z.literal(DRIVE_SCHEMA_IDS.golden),
  generated: z.string().min(10),
  engine: z.literal("ors"),
  profile: z.literal("driving-car"),
  attribution: z.string().min(10),
  sources: z.array(z.strictObject({ file: z.string(), pairs: z.number().int().min(0) })),
  pairs: z.array(goldenPair),
});

export const driveFlag = z.enum(DRIVE_FLAGS);

export type ProfileRow = z.infer<typeof profileRow>;
export type ProfileFile = z.infer<typeof profileFile>;
export type AreaRow = z.infer<typeof areaRow>;
export type AreasFile = z.infer<typeof areasFile>;
export type CrossingRow = z.infer<typeof crossingRow>;
export type CrossingsFile = z.infer<typeof crossingsFile>;
export type SegmentRow = z.infer<typeof segmentRow>;
export type SegmentsFile = z.infer<typeof segmentsFile>;
export type CalibrationCell = z.infer<typeof calibrationCell>;
export type CalibrationFile = z.infer<typeof calibrationFile>;
export type ErrorStats = z.infer<typeof errorStats>;
export type GoldenPair = z.infer<typeof goldenPair>;
export type GoldenFile = z.infer<typeof goldenFile>;
