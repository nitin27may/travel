// The graph index (entity-graph 6 and 8; task EG-I). Pure functions over a loaded capture world: containment (explicit part_of first,
// then covers_areas, never geometry), the transitive closure, the chain of every record (CHAIN_RULES), every derived inverse, stages
// in order, and the requirement refs. The CLI (core/bin/graph.ts) writes the result as data/catalogue/graph/*.json: refs only, no prose,
// no household data, server side only (P8 no bulk files, P9 one data boundary). Nothing under web/ imports this.
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { resolveNode } from "../capture/resolve.ts";
import { primaryRef } from "../capture/records.ts";
import { buildContainment, uniqueTargets } from "../capture/graph.ts";
import type { Basis } from "../capture/graph.ts";
import type { World } from "../capture/records.ts";
import { CHAIN_RULES, RELATION_RULES, typeUnder } from "../schema/capture/relations.ts";
import type { RuleKey } from "../schema/capture/relations.ts";
import type { CaptureRecord } from "../schema/capture/records.ts";

export const GRAPH_DIR = "data/catalogue/graph";
export const GENERATED_LINE = "Generated by node core/bin/graph.ts build. Do not edit.";
export const UNPLACED = "_unplaced";

/** Why a record is in a chain (QG3): the label of the first step that reached it. */
export type Via = "self" | "container" | "start" | "payoff" | "end" | "access" | "primary" | "at" | "on";
export interface ChainEntry { ref: string; via: Via }
export type { Basis };

const STEP_VIA: Partial<Record<RuleKey, Via>> = {
  part_of: "container", starts_at: "start", reaches: "payoff", ends_at: "end", serves: "access", parks_for: "access",
  variant_of: "primary", at: "at", on: "on",
};

export interface GraphIndex {
  world: World;
  /** captured records by primary ref */
  recs: ReadonlyMap<string, CaptureRecord>;
  /** direct containers, nearest first, with how the record got there */
  containers(ref: string): { refs: string[]; basis: Basis | null };
  /** every container up the tree, nearest first */
  containerChain(ref: string): string[];
  /** chain(x) of entity-graph 6.2 with the reason each record is in it */
  chainOf(ref: string): ChainEntry[];
  /** direct members of a container, sorted */
  membersOf(ref: string): string[];
  /** every member at any depth, sorted */
  membersAll(ref: string): string[];
  /** the access offers that apply to a record before the visit-mode and month filters */
  reqOf(ref: string): { ref: string; from: string; via: Via }[];
  /** derived inverses, sorted */
  inv: ReadonlyMap<string, Record<string, string[]>>;
  /** stage order per route */
  stages: ReadonlyMap<string, string[]>;
  cycles: string[][];
  edges: number;
  offerClassOf(ref: string): string | null;
}

const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export function buildIndex(world: World): GraphIndex {
  const p = (r: string): string => primaryRef(world, r);
  const recs = new Map<string, CaptureRecord>();
  for (const [ref, { rec }] of world.cap) recs.set(ref, rec);

  const { containers, containerChain, cycles } = buildContainment(world);
  const tg = (r: CaptureRecord, key: string): string[] => uniqueTargets(world, r, key);

  function chainOf(x: string): ChainEntry[] {
    const seen = new Set<string>();
    const out: ChainEntry[] = [];
    const visit = (ref: string, via: Via): void => {
      if (seen.has(ref)) return;
      seen.add(ref);
      out.push({ ref, via });
      const r = recs.get(ref);
      if (!r) return;
      const rule = CHAIN_RULES.find((c) => c.layer === r.layer && (!c.types || c.types.some((t) => typeUnder(r.type, t))));
      if (!rule) return;
      for (const step of rule.follow) {
        let targets = step.rel === "part_of" ? containers(ref).refs : tg(r, step.rel);
        // 6.2 vs 4.5: a variant that states its own payoff, start or end uses them; one that does not takes the primary's
        if (r.layer === "route" && r.variant_of && ["reaches", "starts_at", "ends_at"].includes(step.rel) && !targets.length) {
          const prim = recs.get(p(r.variant_of));
          if (prim) targets = tg(prim, step.rel);
        }
        if (r.layer === "route" && step.rel === "variant_of" && ["reaches", "starts_at", "ends_at"].some((k) => tg(r, k).length)) targets = [];
        const label = ref === x ? STEP_VIA[step.rel] ?? "container" : via;
        for (const t of targets) {
          if (step.recurse) visit(t, label);
          else if (!seen.has(t)) { seen.add(t); out.push({ ref: t, via: label }); }
        }
      }
    };
    visit(x, "self");
    return out;
  }

  // derived inverses, from the table
  const invSets = new Map<string, Map<string, Set<string>>>();
  const addInv = (ref: string, name: string, v: string): void => {
    let m = invSets.get(ref);
    if (!m) invSets.set(ref, (m = new Map()));
    let s = m.get(name);
    if (!s) m.set(name, (s = new Set()));
    s.add(v);
  };
  let edges = 0;
  for (const [ref, r] of recs) {
    for (const rule of RELATION_RULES) {
      if (rule.shape === "areas") continue;
      for (const t of tg(r, rule.key)) {
        edges++;
        if (rule.key === "part_of") continue; // members, below
        if (rule.symmetric) { addInv(t, rule.key, ref); addInv(ref, rule.key, t); }
        else if (rule.inverse) addInv(t, rule.inverse, ref);
      }
    }
  }
  const inv = new Map<string, Record<string, string[]>>();
  for (const ref of [...invSets.keys()].sort(cmp)) {
    const o: Record<string, string[]> = {};
    for (const name of [...invSets.get(ref)!.keys()].sort(cmp)) o[name] = [...invSets.get(ref)!.get(name)!].sort(cmp);
    inv.set(ref, o);
  }

  // members (direct) and the closure
  const direct = new Map<string, Set<string>>();
  for (const ref of recs.keys()) for (const c of containers(ref).refs) {
    let s = direct.get(c);
    if (!s) direct.set(c, (s = new Set()));
    s.add(ref);
  }
  const membersOf = (ref: string): string[] => [...(direct.get(ref) ?? [])].sort(cmp);
  const allMemo = new Map<string, string[]>();
  function membersAll(ref: string): string[] {
    const hit = allMemo.get(ref);
    if (hit) return hit;
    const seen = new Set<string>([ref]);
    const stack = [ref];
    while (stack.length) for (const m of direct.get(stack.pop()!) ?? []) if (!seen.has(m)) { seen.add(m); stack.push(m); }
    seen.delete(ref);
    const out = [...seen].sort(cmp);
    allMemo.set(ref, out);
    return out;
  }

  // stages: members that are routes of a route, in ends_at/starts_at order
  const stages = new Map<string, string[]>();
  for (const [route, set] of direct) {
    if (recs.get(route)?.layer !== "route") continue;
    const st = [...set].filter((s) => recs.get(s)?.layer === "route").sort(cmp);
    if (!st.length) continue;
    const startOf = (s: string): string | undefined => tg(recs.get(s)!, "starts_at")[0];
    const endOf = (s: string): string | undefined => tg(recs.get(s)!, "ends_at")[0];
    const next = (s: string): string[] => st.filter((o) => o !== s && endOf(s) !== undefined && endOf(s) === startOf(o));
    const hasPrev = (s: string): boolean => st.some((o) => o !== s && next(o).includes(s));
    const ordered: string[] = [];
    for (const head of st.filter((s) => !hasPrev(s))) {
      let cur: string | undefined = head;
      while (cur && !ordered.includes(cur)) { ordered.push(cur); const n: string[] = next(cur); cur = n.length === 1 ? n[0] : undefined; }
    }
    for (const s of st) if (!ordered.includes(s)) ordered.push(s);
    stages.set(route, ordered);
  }

  const classMemo = new Map<string, string | null>();
  const offerClassOf = (ref: string): string | null => {
    const r = recs.get(ref);
    if (!r || r.layer !== "offer") return null;
    let c = classMemo.get(ref);
    if (c === undefined) {
      c = r.offer_class ?? resolveNode(r.type)?.layers.offer?.offer_class ?? null;
      classMemo.set(ref, c);
    }
    return c;
  };

  function reqOf(x: string): { ref: string; from: string; via: Via }[] {
    const out = new Map<string, { ref: string; from: string; via: Via }>();
    if (offerClassOf(x) === "access") return [{ ref: x, from: x, via: "self" }];
    for (const c of chainOf(x)) {
      const i = inv.get(c.ref);
      for (const o of [...(i?.offers_at ?? []), ...(i?.offers_on ?? [])]) if (offerClassOf(o) === "access" && !out.has(o)) out.set(o, { ref: o, from: c.ref, via: c.via });
    }
    return [...out.values()].sort((a, b) => cmp(a.ref, b.ref));
  }

  return { world, recs, containers, containerChain, chainOf, membersOf, membersAll, reqOf, inv, stages, cycles, edges, offerClassOf };
}

/** The nearest protected area of a record: the first nature.protected.* record in its chain (6.2). */
export function nearestProtected(g: GraphIndex, ref: string): string | null {
  for (const c of g.chainOf(ref)) {
    const r = g.recs.get(c.ref);
    if (r && typeUnder(r.type, "nature.protected")) return c.ref;
  }
  return null;
}

