export interface GraphFile { path: string; text: string }
export interface BuildReport {
  files: GraphFile[];
  records: number;
  edges: number;
  containers: number;
  withContainer: number;
  byKind: Record<string, number>;
  cycles: string[][];
}

const kindOf = (type: string): string => type.split(".").slice(0, 2).join(".");

/** One section per line group: `"key": {` then one entry per line, entries compact. Stable, diffable. */
function format(doc: Record<string, unknown>): string {
  const lines: string[] = ["{"];
  const keys = Object.keys(doc);
  keys.forEach((k, i) => {
    const v = doc[k];
    const comma = i < keys.length - 1 ? "," : "";
    if (v && typeof v === "object" && !Array.isArray(v) && k !== "counts") {
      const ents = Object.entries(v as Record<string, unknown>);
      if (!ents.length) lines.push(` ${JSON.stringify(k)}: {}${comma}`);
      else {
        lines.push(` ${JSON.stringify(k)}: {`);
        ents.forEach(([ek, ev], j) => lines.push(`  ${JSON.stringify(ek)}: ${JSON.stringify(ev)}${j < ents.length - 1 ? "," : ""}`));
        lines.push(` }${comma}`);
      }
    } else lines.push(` ${JSON.stringify(k)}: ${JSON.stringify(v)}${comma}`);
  });
  lines.push("}");
  return lines.join("\n") + "\n";
}

export function buildFiles(world: World): BuildReport {
  const g = buildIndex(world);
  const slugs = readSlugs(world.root);
  const refs = [...g.recs.keys()].sort(cmp);

  // country: the first record in the chain with an area_id (own first), else a covered area; else _unplaced
  const chains = new Map<string, ChainEntry[]>();
  const countryOf = new Map<string, string>();
  const areaOfRec = (ref: string): string | null => {
    const r = g.recs.get(ref);
    return r?.area_id ?? r?.covers_areas?.[0] ?? null;
  };
  for (const ref of refs) {
    const ch = g.chainOf(ref);
    chains.set(ref, ch);
    const a = ch.map((c) => areaOfRec(c.ref)).find((x) => x);
    countryOf.set(ref, a ? a.split("/")[0]! : UNPLACED);
  }
  const home = (ref: string, hint: string): string => countryOf.get(ref) ?? hint;

  type Shard = { nodes: Record<string, unknown>; chain: Record<string, string[]>; inv: Record<string, Record<string, string[]>>; members: Record<string, Record<string, string[]>>; members_all: Record<string, Record<string, string[]>>; containers: Record<string, string[]>; stages: Record<string, string[]>; req: Record<string, { ref: string; from: string; via: string }[]> };
  const shards = new Map<string, Shard>();
  const shard = (cc: string): Shard => {
    let s = shards.get(cc);
    if (!s) shards.set(cc, (s = { nodes: {}, chain: {}, inv: {}, members: {}, members_all: {}, containers: {}, stages: {}, req: {} }));
    return s;
  };
  const byKind = (list: string[]): Record<string, string[]> => {
    const o: Record<string, string[]> = {};
    for (const m of list) { const r = g.recs.get(m); const k = r ? `${r.layer}:${kindOf(r.type)}` : "external"; (o[k] ??= []).push(m); }
    return Object.fromEntries(Object.keys(o).sort(cmp).map((k) => [k, o[k]!]));
  };

  const counts: Record<string, number> = {};
  let withContainer = 0;
  const containerSet = new Set<string>();
  const digest = createHash("sha256");
  for (const ref of refs) {
    const r = g.recs.get(ref)!;
    const cc = countryOf.get(ref)!;
    const s = shard(cc);
    s.nodes[ref] = [r.layer, r.type, r.area_id ?? null, slugs[ref] ?? null];
    const ch = chains.get(ref)!.map((c) => c.ref);
    if (ch.length > 1) s.chain[ref] = ch;
    const up = g.containerChain(ref);
    if (up.length) { s.containers[ref] = up; withContainer++; }
    const req = g.reqOf(ref);
    if (req.length) s.req[ref] = req;
    counts[`${r.layer}:${kindOf(r.type)}`] = (counts[`${r.layer}:${kindOf(r.type)}`] ?? 0) + 1;
    digest.update(JSON.stringify([ref, r.layer, r.type, r.area_id ?? null, g.containers(ref), ch, req]) + "\n");
  }
  for (const [ref, o] of g.inv) shard(home(ref, UNPLACED)).inv[ref] = o;
  for (const ref of [...refs, ...[...g.inv.keys()].filter((k) => !g.recs.has(k))]) {
    const m = g.membersOf(ref);
    if (!m.length) continue;
    containerSet.add(ref);
    const cc = home(ref, countryOf.get(m[0]!) ?? UNPLACED);
    shard(cc).members[ref] = byKind(m);
    shard(cc).members_all[ref] = byKind(g.membersAll(ref));
  }
  // containers outside the capture (a place ref with no record) still have members
  for (const m of refs) for (const c of g.containers(m).refs) if (!g.recs.has(c) && !containerSet.has(c)) {
    containerSet.add(c);
    const cc = countryOf.get(m) ?? UNPLACED;
    shard(cc).members[c] = byKind(g.membersOf(c));
    shard(cc).members_all[c] = byKind(g.membersAll(c));
  }
  for (const [route, st] of g.stages) shard(home(route, UNPLACED)).stages[route] = st;

  const sortRec = <T>(o: Record<string, T>): Record<string, T> => Object.fromEntries(Object.keys(o).sort(cmp).map((k) => [k, o[k]!]));
  const files: GraphFile[] = [];
  const ccs = [...shards.keys()].sort(cmp);
  for (const cc of ccs) {
    const s = shards.get(cc)!;
    files.push({
      path: `${GRAPH_DIR}/${cc}.json`,
      text: format({ generated: GENERATED_LINE, schema: "catalogue-graph-shard/1", country: cc, nodes: sortRec(s.nodes), chain: sortRec(s.chain), containers: sortRec(s.containers), inv: sortRec(s.inv), members: sortRec(s.members), members_all: sortRec(s.members_all), stages: sortRec(s.stages), req: sortRec(s.req) }),
    });
  }
  files.unshift({
    path: `${GRAPH_DIR}/index.json`,
    text: format({ generated: GENERATED_LINE, schema: "catalogue-graph/1", inputs: digest.digest("hex").slice(0, 16), counts: { records: refs.length, edges: g.edges, containers: containerSet.size }, shards: ccs }),
  });
  return { files, records: refs.length, edges: g.edges, containers: containerSet.size, withContainer, byKind: sortRec(counts), cycles: g.cycles };
}

function readSlugs(root: string): Record<string, string> {
  const p = join(root, "data", "catalogue", "slugs.json");
  if (!existsSync(p)) return {};
  try {
    const d = JSON.parse(readFileSync(p, "utf8")) as { places?: { slugs?: Record<string, string> } };
    return d.places?.slugs ?? {};
  } catch {
    return {};
  }
}
