// JSON Schema export: one 2020-12 document, $defs keyed "<family>.<table>" and sorted, built with
// z.toJSONSchema per table plus the table meta copied under x-* keys (plan 2.5).
import { z } from "zod";
import { LOCATIONS_SCHEMA_VERSION } from "./locations.ts";
import { REGISTRY } from "./index.ts";
import { TRIP_SCHEMA_VERSION } from "./trip.ts";
import type { Table } from "./meta.ts";

export type JsonObject = { [key: string]: any };

export function tableToJsonSchema(t: Table): JsonObject {
  const js = z.toJSONSchema(t.schema, {
    target: "draft-2020-12",
    io: "input",
    unrepresentable: "throw",
    override: (ctx) => {
      // z.iso.date() and z.iso.datetime() export a long calendar regex next to `format`; the format is enough
      const s = ctx.jsonSchema as JsonObject;
      if (s.format === "date" || s.format === "date-time") delete s.pattern;
      // z.number().int() exports the safe-integer range as bounds; drop it so only real limits remain
      if (s.maximum === Number.MAX_SAFE_INTEGER) delete s.maximum;
      if (s.minimum === Number.MIN_SAFE_INTEGER) delete s.minimum;
    },
  }) as JsonObject;
  delete js.$schema;
  return {
    ...js,
    "x-family": t.family,
    "x-table": t.name,
    "x-single": t.meta.single === true,
    "x-pk": t.meta.pk,
    "x-sql": t.meta.sql,
    "x-ui": t.meta.ui,
    "x-private": t.meta.private,
    "x-rules": t.meta.rules,
  };
}

export function buildSchemaJson(): JsonObject {
  const defs: JsonObject = {};
  for (const t of [...REGISTRY].sort((a, b) => a.key.localeCompare(b.key))) defs[t.key] = tableToJsonSchema(t);
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://nks-travel.pages.dev/schema.json",
    title: "Travel platform data schema",
    description: "Generated by node core/bin/schema.ts generate from core/src/schema. Do not edit by hand.",
    "x-schema-versions": { trip: TRIP_SCHEMA_VERSION, catalog: 1, locations: LOCATIONS_SCHEMA_VERSION },
    $defs: defs,
  };
}

export function schemaJsonText(): string {
  return JSON.stringify(buildSchemaJson(), null, 2) + "\n";
}
