// SQLite/D1 DDL generated from the exported JSON Schema (not from Zod internals).
import type { JsonObject } from "./export.ts";

const SQL_TYPE: Record<string, string> = {
  text: "TEXT", date: "TEXT", datetime: "TEXT", hhmm: "TEXT", tz: "TEXT", pdate: "TEXT",
  int: "INTEGER", month: "INTEGER", offset: "INTEGER", bool: "INTEGER", real: "REAL", json: "TEXT",
};

const QUOTE = new Set([
  "end", "return", "window", "order", "group", "index", "key", "references", "check", "unique", "primary",
  "default", "transaction", "values", "match", "action", "to", "from",
]);
export const ident = (s: string): string => (QUOTE.has(s) ? `"${s}"` : s);

interface Col {
  name: string;
  type: string;
  nullable: boolean;
  schema: JsonObject;
  fk?: string;
}

function columnsOf(def: JsonObject): Col[] {
  return Object.entries<JsonObject>(def.properties).map(([name, prop]) => {
    const nullBranch = Array.isArray(prop.anyOf) ? prop.anyOf.findIndex((b: JsonObject) => b.type === "null") : -1;
    const nullInType = Array.isArray(prop.type) && prop.type.includes("null");
    const inner: JsonObject = nullBranch >= 0 ? prop.anyOf.find((_: JsonObject, i: number) => i !== nullBranch) : prop;
    const type = (prop["x-type"] ?? inner["x-type"]) as string | undefined;
    if (!type || !(type in SQL_TYPE)) throw new Error(`column ${name} has no usable x-type (${String(type)})`);
    return { name, type, nullable: nullBranch >= 0 || nullInType, schema: inner, fk: prop["x-fk"] };
  });
}

const sqlString = (v: string): string => `'${v.replace(/'/g, "''")}'`;

function columnDdl(c: Col): string {
  const parts = [ident(c.name), SQL_TYPE[c.type]];
  if (!c.nullable) parts.push("NOT NULL");
  const n = ident(c.name);
  if (c.type === "bool") parts.push(`CHECK (${n} IN (0,1))`);
  else if (c.type === "json") parts.push(`CHECK (json_valid(${n}))`);
  else if (Array.isArray(c.schema.enum)) parts.push(`CHECK (${n} IN (${c.schema.enum.map(sqlString).join(", ")}))`);
  else if ((c.type === "int" || c.type === "real") && (c.schema.minimum !== undefined || c.schema.maximum !== undefined)) {
    const lo = c.schema.minimum !== undefined ? `${n} >= ${c.schema.minimum}` : "";
    const hi = c.schema.maximum !== undefined ? `${n} <= ${c.schema.maximum}` : "";
    parts.push(`CHECK (${[lo, hi].filter(Boolean).join(" AND ")})`);
  }
  return parts.join(" ");
}

export function ddlText(schema: JsonObject): string {
  const defs: JsonObject = schema.$defs;
  const sqlName = (d: JsonObject): string => d["x-sql"].name ?? d["x-table"];
  const byName = new Map<string, JsonObject>();
  for (const d of Object.values<JsonObject>(defs)) {
    if (d["x-family"] === "sidecar") continue;
    const n = sqlName(d);
    if (byName.has(n)) throw new Error(`two tables share the SQL name ${n}; set meta.sql.name on one of them`);
    byName.set(n, d);
  }
  const order = ["locations", "catalog", "trip"];
  const tables = [...byName.values()].sort(
    (a, b) => order.indexOf(a["x-family"]) - order.indexOf(b["x-family"]) || sqlName(a).localeCompare(sqlName(b)),
  );
  // trips first within the trip family so readers meet the parent table before its children
  tables.sort((a, b) => (a["x-family"] === "trip" && b["x-family"] === "trip" ? Number(sqlName(b) === "trips") - Number(sqlName(a) === "trips") : 0));

  const out: string[] = [
    "-- Generated by node core/bin/schema.ts generate from core/src/schema. Do not edit by hand.",
    "-- Trip tables carry a leading trip_id; catalog and locations tables do not.",
    "-- Loaded by tools/tests/test_schema_sqlite.py. If the local SQLite has no JSON1, the test strips",
    "-- the json_valid checks.",
    "PRAGMA foreign_keys = ON;",
  ];
  const indexes: string[] = [];

  for (const d of tables) {
    const name = sqlName(d);
    const family: string = d["x-family"];
    const isTrips = name === "trips";
    const tripScoped = family === "trip" && !isTrips;
    const lines: string[] = [];
    const lead: string[] = [];
    if (tripScoped) lead.push("trip_id");
    for (const l of d["x-sql"].lead ?? []) lead.push(l.name);
    if (tripScoped) lines.push("trip_id TEXT NOT NULL REFERENCES trips(slug)");
    for (const l of d["x-sql"].lead ?? []) lines.push(l.ddl);
    const cols = columnsOf(d);
    for (const c of cols) lines.push(columnDdl(c));
    const pk = [...lead, ...(d["x-pk"] as string[])];
    if (pk.length > 0) lines.push(`PRIMARY KEY (${pk.map(ident).join(", ")})`);
    for (const c of cols) {
      if (!c.fk || c.type === "json") continue;
      const [tTable, tCol] = c.fk.split(".");
      const target = byName.get(tTable);
      if (!target) throw new Error(`${name}.${c.name}: foreign key target ${c.fk} is not a table`);
      if (!(target.properties as JsonObject)[tCol]) throw new Error(`${name}.${c.name}: ${tTable} has no column ${tCol}`);
      const targetTrip = target["x-family"] === "trip" && tTable !== "trips";
      if (tripScoped && targetTrip) {
        lines.push(`FOREIGN KEY (trip_id, ${ident(c.name)}) REFERENCES ${tTable}(trip_id, ${ident(tCol)})`);
      } else {
        lines.push(`FOREIGN KEY (${ident(c.name)}) REFERENCES ${tTable}(${ident(tCol)})`);
      }
    }
    for (const chk of d["x-sql"].checks ?? []) lines.push(chk);
    out.push("", `CREATE TABLE ${name} (`, lines.map((l) => `  ${l}`).join(",\n"), ");");
    for (const idx of d["x-sql"].indexes ?? []) {
      const icols = [...(tripScoped ? ["trip_id"] : []), ...idx];
      indexes.push(`CREATE INDEX idx_${name}_${idx.join("_")} ON ${name} (${icols.map(ident).join(", ")});`);
    }
  }
  if (indexes.length > 0) out.push("", ...indexes);
  return out.join("\n") + "\n";
}
