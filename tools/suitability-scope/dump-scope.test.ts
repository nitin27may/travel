// Writes data/suitability/scope.json: the 207 in-scope refs of research/method/suitability.md section 7, taken
// from the public adapter. Run from the repo root:
//   pnpm --dir web exec vitest run -c ../tools/suitability-scope/vitest.config.mts
// core/ cannot import web/, so the suitability migration reads this manifest. Re-run it when a trip's items change;
// S1 owns keeping it in step with the adapter.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { it } from 'vitest';
import { buildPlaces, normName } from '@/lib/public/places';
import { buildTrips } from '@/lib/public/trips';
import { DropLog } from '@/lib/public/dateless';
import { loadSources } from '@/lib/public/sources';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../data/suitability/scope.json');
const IN_SCOPE_CATEGORIES = ['trails', 'activities', 'sights'] as const;
const SKIP_PLACE_KINDS = new Set(['eatery', 'stay', 'area']);

type Source = { protoId?: string; locationId?: string; legacy?: { folder: string; dataset: string; id: string } };
interface Item { ref: string; key: string | null; trip: string; kind: string; name: string; days: number[]; source: Source }

it('dumps the suitability scope', () => {
  const src = loadSources();
  const log = new DropLog();
  const pb = buildPlaces(src, log);
  const tb = buildTrips(src, pb, log);
  const protoOf = new Map([...pb.byProtoId].map(([id, slug]) => [slug, id]));
  const locOf = new Map([...pb.byLocationId].map(([id, slug]) => [slug, id]));
  const placeSource = (slug: string): Source => ({ ...(protoOf.has(slug) ? { protoId: protoOf.get(slug) } : {}), ...(locOf.has(slug) ? { locationId: locOf.get(slug) } : {}) });
  const rk = src.rockies;
  const idByName = (rows: Record<string, unknown>[]) => new Map(rows.map((r) => [String(r.name), String(r.id)]));
  const rockies = rk ? { trails: idByName(rk.trails), sights: idByName(rk.sights), adventures: idByName(rk.adventures) } : null;
  const items: Item[] = [];
  const places = new Set(pb.places.map((p) => p.slug));
  // trail pages built from capture route records keep the ref their sidecars already use (the capture ref or the legacy dataset ref)
  const captureBorn = new Set(pb.byCaptureRef.values());

  for (const trip of tb.trips) {
    if (trip.slug === 'dolomites-2027') {
      for (const p of pb.places.filter((x) => x.trips.some((t) => t.slug === trip.slug) && !SKIP_PLACE_KINDS.has(x.kind) && !captureBorn.has(x.slug))) {
        items.push({ ref: `place/${p.slug}`, key: p.slug, trip: trip.slug, kind: p.kind, name: p.name, days: [], source: placeSource(p.slug) });
      }
      continue;
    }
    for (const c of IN_SCOPE_CATEGORIES) {
      for (const raw of trip.categories[c]) {
        // a trail page built from a capture record is not a place of the scope: its item keeps the key and ref it had before the page
        const born = !!raw.placeSlug && captureBorn.has(raw.placeSlug);
        const it = born ? { ...raw, placeSlug: null, key: `${raw.kind}:${normName(raw.name)}` } : raw;
        const source: Source = it.placeSlug ? placeSource(it.placeSlug) : {};
        if (trip.slug === 'canadian-rockies-2029' && rockies) {
          const dataset = it.kind === 'trail' ? 'trails' : it.kind === 'sight' ? 'sights' : 'adventures';
          const id = rockies[dataset].get(it.name);
          if (!id) throw new Error(`Rockies item "${it.name}" is not in ${dataset}.json`);
          source.legacy = { folder: 'canadian-rockies-sept-2029', dataset, id };
        }
        const ref = it.placeSlug && places.has(it.placeSlug)
          ? `place/${it.placeSlug}`
          : source.legacy ? `legacy/${source.legacy.folder}/${source.legacy.dataset}/${source.legacy.id}` : `trip/${trip.slug}/${it.key}`;
        items.push({ ref, key: it.key, trip: trip.slug, kind: it.kind, name: it.name, days: it.days, source });
      }
    }
  }
  items.sort((a, b) => a.trip.localeCompare(b.trip) || a.ref.localeCompare(b.ref));
  const dup = items.map((i) => i.ref).filter((r, i, a) => a.indexOf(r) !== i);
  if (dup.length) throw new Error(`duplicate refs: ${dup.join(', ')}`);
  const doc = {
    schema: 'suitability-scope/1',
    note: 'Generated by tools/suitability-scope/dump-scope.test.ts from the public adapter. Do not edit by hand.',
    places: pb.places.map((p) => p.slug).sort(),
    items,
  };
  writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n');
});
