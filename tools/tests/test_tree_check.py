def load():
    spec = importlib.util.spec_from_file_location("tree_check_under_test", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture()
def repo(tmp_path, monkeypatch):
    mod = load()
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    for rel, text in BASE_FILES.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    (tmp_path / "tc.json").write_text(json.dumps(CONTRACT))
    (tmp_path / "pins.json").write_text(json.dumps({"pins": {}, "raised": []}))
    monkeypatch.setattr(mod, "ROOT", tmp_path)
    monkeypatch.setattr(mod, "CONTRACT", tmp_path / "tc.json")
    monkeypatch.setattr(mod, "PINS", tmp_path / "pins.json")
    # tc.json and pins.json sit at the fixture root, so keep them out of the file list.
    (tmp_path / ".gitignore").write_text("tc.json\npins.json\n")
    assert mod.main(["--write", "--reason", "fixture"]) == 0

    class R:
        root = tmp_path
        m = mod

        def add(self, rel, text=None):
            text = text if text is not None else f"unique content of {rel}\n"
            p = tmp_path / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)

        def rules(self):
            return {v[0] for v in mod.all_violations(mod.listed(), mod.load_contract())}

        def run(self, capsys):
            rc = mod.main([])
            return rc, capsys.readouterr()

    return R()


