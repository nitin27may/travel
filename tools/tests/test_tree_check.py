def test_baseline_suppresses_and_reports_stale(repo, capsys):
    repo.add("research/stray.md")
    c = json.loads((repo.root / "tc.json").read_text())
    c["baseline"] = {"2": [{"key": "research/stray.md", "reason": "test"}, {"key": "research/gone.md", "reason": "stale"}]}
    (repo.root / "tc.json").write_text(json.dumps(c))
    rc, out = repo.run(capsys)
    assert rc == 0 and "no longer fire" in out.out and "research/gone.md" in out.out


def test_real_tree_passes_and_is_fast():
    import time

    t = time.time()
    r = subprocess.run([sys.executable, str(SCRIPT)], cwd=REAL_ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    assert time.time() - t < 10
