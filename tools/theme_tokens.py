#!/usr/bin/env python3
"""Generate web/app/themes.css from the Trailhead foundation tokens.

    python3 tools/theme_tokens.py            write web/app/themes.css
    python3 tools/theme_tokens.py --check    exit 1 if the file would change

Source of truth: docs/v2/design/foundation/tokens.json (values) and tokens.md (rules). Colour lives ONLY
in the generated file; components use the role names (--ink, --accent, --crit ...), never a literal.
Stdlib only; the output is deterministic.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "docs" / "v2" / "design" / "foundation" / "tokens.json"
OUT = ROOT / "web" / "app" / "themes.css"

HEADER = "/* GENERATED by tools/theme_tokens.py from docs/v2/design/foundation/tokens.json. Do not edit. Colour lives only here. */\n"

# Colours that are not themed and not in tokens.json: the dark band under photo text (tokens.md 2.2,
# kicker-on-photo row; components 5.1 gradient 10% to 85%).
PHOTO_SCRIM = {
    "--photo-scrim-top": "rgba(11, 17, 25, 0.1)",
    "--photo-scrim-bottom": "rgba(11, 17, 25, 0.85)",
}

# Derived map tokens (tokens.md 5): expressed with the role names so the theme switch carries them.
MAP_DERIVED = {
    "--map-border": "color-mix(in srgb, var(--muted) 60%, transparent)",
    "--map-label": "var(--ink-2)",
    "--map-route-dim": "color-mix(in srgb, var(--map-route) 28%, transparent)",
    "--map-stop": "var(--ink)",
    "--map-select-ring": "var(--accent)",
}

# Which map keys become --map-* and which become --globe-pin*.
MAP_KEYS = ("land", "high", "wood", "shade", "contour", "water", "casing", "halo", "route", "route-pick", "pin", "pin-ink")
GLOBE_KEYS = ("globe-pin", "globe-pin-ink", "globe-pin-pick", "globe-pin-pick-ink", "globe-ocean", "globe-land", "globe-wood", "globe-halo", "globe-edge", "globe-dim")

# Type tokens whose phone size differs (tokens.json "phone"); emitted again under the phone breakpoint.
PHONE_MAX = 639


def load(path: Path = TOKENS) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def block(selector: str, decls: list[tuple[str, str]], indent: str = "") -> str:
    body = "".join(f"{indent}  {k}: {v};\n" for k, v in decls)
    return f"{indent}{selector} {{\n{body}{indent}}}\n"


def num(n: float) -> str:
    return str(int(n)) if float(n).is_integer() else str(n)


def px(n: float) -> str:
    return f"{num(n)}px"


def family_var(family: str) -> str:
    return {"display": "var(--font-display)", "serif": "var(--font-body)", "mono": "var(--font-mono)"}[family]


def type_shorthand(t: dict, size: float | None = None) -> str:
    style = "italic " if t.get("style") == "italic" else ""
    return f"{style}{t['weight']} {px(size if size is not None else t['size'])}/{num(t['line'])} {family_var(t['family'])}"


def colour_decls(theme: dict, name: str, tokens: dict) -> list[tuple[str, str]]:
    colours = tokens["color"][theme]
    decls: list[tuple[str, str]] = [("color-scheme", "light" if theme in ("light", "sunlight") else "dark")]
    if theme == "sunlight":
        base = tokens["color"]["light"]
        merged = {**base, **{k: v for k, v in colours.items() if k not in ("extends", "note")}}
    else:
        merged = colours
    decls += [(f"--{k}", v) for k, v in merged.items()]
    return decls


def elevation_decls(theme: str, tokens: dict) -> list[tuple[str, str]]:
    key = "dark" if theme == "dark" else "light"
    e = tokens["elevation"][key]
    return [("--e-0", "none"), ("--e-1", e["e1"]), ("--e-2", e["e2"]), ("--e-3", e["e3"])]


def map_decls(theme: str, tokens: dict) -> list[tuple[str, str]]:
    key = "dark" if theme == "dark" else "light"
    m = tokens["color"]["map"][key]
    decls = [(f"--map-{k}", m[k]) for k in MAP_KEYS]
    decls += [(f"--{k}", m[k]) for k in GLOBE_KEYS]
    decls += list(MAP_DERIVED.items())
    return decls


def theme_block(theme: str, tokens: dict) -> str:
    selector = ':root,\n[data-theme="light"]' if theme == "light" else f'[data-theme="{theme}"]'
    decls = colour_decls(theme, theme, tokens) + elevation_decls(theme, tokens) + map_decls(theme, tokens)
    decls.append(("--img", "0.92" if theme == "dark" else "1"))
    return block(selector, decls)


def shared_decls(tokens: dict) -> list[tuple[str, str]]:
    d: list[tuple[str, str]] = []
    fonts, fb = tokens["font"], tokens["font"]["fallbacks"]
    d.append(("--font-display", f"'{fonts['display']['family']}', {fb['display']}"))
    d.append(("--font-body", f"'{fonts['serif']['family']}', {fb['serif']}"))
    d.append(("--font-mono", f"'{fonts['mono']['family']}', {fb['mono']}"))
    # trip identity (tokens.md 4): same in both themes; ring, bar or square with a keyline, never text
    for k, v in tokens["color"]["identity"].items():
        if k == "rule":
            continue
        d.append((f"--id-{k}", v))
    d.extend(PHOTO_SCRIM.items())
    for k, t in tokens["type"].items():
        if k == "rules":
            continue
        d.append((f"--t-{k}", type_shorthand(t)))
        if "tracking" in t:
            d.append((f"--t-{k}-tracking", t["tracking"]))
        if t.get("transform"):
            d.append((f"--t-{k}-transform", t["transform"]))
    d.append(("--t-tab-current-weight", str(tokens["type"]["tab"]["current-weight"])))
    for k, v in tokens["space"].items():
        d.append((f"--s-{k}", px(v)))
    for k, v in tokens["radius"].items():
        d.append((f"--r-{k}", px(v)))
    b = tokens["border"]
    d += [("--b-hairline", b["hairline"]), ("--b-control", b["control"]), ("--b-selected", b["selected"]), ("--b-dashed", b["dashed"])]
    f = tokens["focus"]
    d += [("--focus-ring", f["outline"]), ("--focus-offset", px(f["offset"])), ("--focus-in-header", f["in-header"])]
    for k, v in tokens["z"].items():
        d.append((f"--z-{k}", str(v)))
    lay = tokens["layout"]
    d += [
        ("--max-content", px(lay["max-content"])),
        ("--margin", px(lay["margin-desktop"])),
        ("--header-h", px(lay["header-h"])),
        ("--tripbar-h", px(lay["tripbar-h"])),
        ("--phone-header-h", px(lay["phone-header-h"])),
        ("--phone-bottombar-h", px(lay["phone-bottombar-h"])),
        ("--side-sheet-w", px(lay["side-sheet-w"])),
        ("--side-sheet-photo-h", px(lay["side-sheet-photo-h"])),
        ("--card-gap", px(lay["card-gap"])),
    ]
    t = tokens["touch"]
    d += [("--touch-min", px(t["min"])), ("--touch-gap", px(t["gap"])), ("--dense-row", px(t["dense-row"]))]
    m = tokens["motion"]
    d += [
        ("--d-fast", f"{m['d-fast']}ms"),
        ("--d-base", f"{m['d-base']}ms"),
        ("--d-sheet", f"{m['d-sheet']}ms"),
        ("--d-sheet-close", f"{m['d-sheet-close']}ms"),
        ("--d-page", f"{m['d-page']}ms"),
        ("--d-count", f"{m['d-count']}ms"),
        ("--d-globe", f"{m['d-globe']}ms"),
        ("--e-out", m["e-out"]),
        ("--e-in", m["e-in"]),
        ("--e-std", m["e-std"]),
        ("--spring-stiffness", str(m["spring"]["stiffness"])),
        ("--spring-damping", str(m["spring"]["damping"])),
        ("--spring-mass", str(m["spring"]["mass"])),
    ]
    return d


def phone_decls(tokens: dict) -> list[tuple[str, str]]:
    return [(f"--t-{k}", type_shorthand(t, t["phone"])) for k, t in tokens["type"].items() if k != "rules" and "phone" in t]


def reduced_motion(tokens: dict) -> str:
    # tokens.md 11: every move becomes a 120 ms fade; springs become 150 ms --e-std
    fast = f"{tokens['motion']['d-fast']}ms"
    decls = [(f"--d-{k}", fast) for k in ("base", "sheet", "sheet-close", "page", "count", "globe")]
    decls += [("--d-spring", "150ms"), ("--reduced-motion", "1")]
    return "@media (prefers-reduced-motion: reduce) {\n" + block(":root", decls, "  ") + "}\n"


def render(tokens: dict | None = None) -> str:
    tokens = tokens or load()
    parts = [HEADER]
    parts.append(block(":root", shared_decls(tokens) + [("--reduced-motion", "0")]))
    parts.append(theme_block("light", tokens))
    parts.append(theme_block("dark", tokens))
    parts.append(theme_block("sunlight", tokens))
    parts.append(f"@media (max-width: {PHONE_MAX}px) {{\n" + block(":root", phone_decls(tokens), "  ") + "}\n")
    parts.append(reduced_motion(tokens))
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run python3 tools/theme_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
