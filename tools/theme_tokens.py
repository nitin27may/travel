HEADER = "/* GENERATED by tools/theme_tokens.py. Do not edit. Colour lives only here. */\n"


def parse_tokens(css: str) -> dict[str, str]:
    """The custom properties declared in the first :root block of a legacy theme."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    m = re.search(r":root\s*\{(.*?)\}", css, flags=re.S)
    if not m:
        raise ValueError("no :root block")
    return {k: v.strip() for k, v in re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", m.group(1))}


def legacy_themes(themes: Path = THEMES) -> dict[str, dict[str, str]]:
    return {p.stem: parse_tokens(p.read_text(encoding="utf-8")) for p in sorted(themes.glob("*.css"))}


def block(selector: str, tokens: dict[str, str]) -> str:
    body = "".join(f"  {k}: {v};\n" for k, v in tokens.items())
    return f"{selector} {{\n{body}}}\n"


def render(themes: dict[str, dict[str, str]]) -> str:
    parts = [HEADER]
    parts.append(block(':root,\n[data-theme="shell"]', {**SHELL_COMMON, **SHELL_DARK, "color-scheme": "dark"}))
    parts.append(block('[data-theme="shell-light"]', {**SHELL_COMMON, **SHELL_LIGHT, "color-scheme": "light"}))
    for name, tokens in themes.items():
        parts.append(block(f'[data-theme="{name}"]', tokens))
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(legacy_themes())
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run python3 tools/theme_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
