#!/usr/bin/env python3
"""Folder-contract guard (CLN-5; docs/v2/CLEANUP-PLAN.md section CLN-5, rules 1-11).

Mechanical and offline: reads the file list from git (tracked plus untracked-but-not-ignored, the way tools/cons/hardcode_scan.py
does) and fails when a file lands in the wrong place, is duplicated, or names a path that no longer exists. It only reports; it never
moves or deletes. Allowlists and the baseline of today's known exceptions (one reason per entry) live in tools/tree_contract.json;
the legacy freeze pins live in tools/legacy-freeze.json.

    python3 tools/tree_check.py                 # check (default): exit 1 with what to do
    python3 tools/tree_check.py --list          # every violation, baselined or not
    python3 tools/tree_check.py --write --reason "why"
                                                # refresh the legacy pins (rule 11) and append the reason to the 'raised' log

Rules: 1 top-level folders, 2 research root, 3 docs root and the research stub, 4 research/types generated only, 5 trip index,
6 skills and agent, 7 duplicate files (docs/ and research/), 8 images named and under 1.5 MB, 9 nothing live links into
docs/archive, 10 dead paths and broken links, 11 legacy freeze.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = Path(__file__).with_name("tree_contract.json")
PINS = Path(__file__).with_name("legacy-freeze.json")
sys.path.insert(0, str(Path(__file__).resolve().parent))

GENERATED_HEADER = "<!-- Generated by `node core/bin/capture.ts build`"
TEXT_EXT = {".md", ".html", ".txt", ".json", ".ts", ".tsx", ".mjs", ".py", ".css", ".sh"}
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".webp", ".svg", ".gif"}
MAX_IMAGE = 1_500_000
FREEZE_MSG = "new HTML goes in web/; legacy is frozen (CLEANUP D20..D22)"

# Rule 10 scope: where authored code and docs may name a repo path. Tests and fixtures invent paths, so they are not scanned.
SCAN_PREFIXES = ("core/", "web/", "tools/", "data/", ".claude/", "research/")
SCAN_FILES = {"CLAUDE.md", "README.md", "HANDOVER.md"}
SCAN_EXT = {".md", ".ts", ".tsx", ".mjs", ".js", ".py", ".sh", ".css", ".txt", ".yaml", ".yml"}
SKIP_SCAN = re.compile(
    r"(^|/)(tests?|__tests__|fixtures?|e2e|node_modules|data-snapshots)/|\.(test|spec)\.[a-z]+$|(^|/)test_[^/]+\.py$|(^|/)conftest\.py$"
    r"|baseline\.json$|^tools/tree_check\.py$|^tools/relink\.py$|^research/audits/sun-audit"
)
# Runtime locations that exist on a working machine only.
RUNTIME = re.compile(r"(\.cache|\.env|^web/out|\.next|\.generated|public/img|\.site|test-results|\.tile-cache|node_modules)")
PATH_RE = re.compile(r"(?<![\w./@~-])((?:core|data|docs|research|tools|web|legacy|prototype)/[A-Za-z0-9_./\-]*[A-Za-z0-9_/])")


def git_lines(*args: str) -> list[str]:
    raw = subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True).stdout.decode("utf-8", "replace")
    return [x for x in raw.split("\0") if x]


def listed() -> list[str]:
    files = git_lines("ls-files", "-z", "--cached", "--others", "--exclude-standard")
    return sorted({f for f in files if (ROOT / f).is_file() or (ROOT / f).is_symlink()})


def load_contract() -> dict:
    return json.loads(CONTRACT.read_text(encoding="utf-8"))


def hash_files(paths: list[str]) -> dict[str, str]:
    """Git blob hash of the working-tree bytes (so an unstaged edit is seen too)."""
    if not paths:
        return {}
    out = subprocess.run(["git", "-C", str(ROOT), "hash-object", "--stdin-paths"], input="\n".join(paths) + "\n",
                         check=True, capture_output=True, text=True).stdout.split()
    return dict(zip(paths, out))


Viol = tuple[str, str, str]  # (rule, key, message)


# ----- rules 1-9 ------------------------------------------------------------------------------------------------------------------------
def rule1(files: list[str], c: dict) -> list[Viol]:
    allowed = set(c["top_level_folders"])
    tops = {f.split("/")[0] for f in files if "/" in f}
    return [("1", t, f"new top-level folder '{t}/'. The folders are {' '.join(sorted(allowed))}; put the files under one of them "
                     f"(docs/v2/CLEANUP-PLAN.md 5.1), or ask the owner to extend top_level_folders in tools/tree_contract.json")
            for t in sorted(tops - allowed)]


def rule2(files: list[str], c: dict) -> list[Viol]:
    ok_files, ok_dirs = set(c["research_root_files"]), set(c["research_root_dirs"])
    out: list[Viol] = []
    seen: set[str] = set()
    for f in files:
        if not f.startswith("research/"):
            continue
        parts = f.split("/")
        name = parts[1]
        if name in seen:
            continue
        if len(parts) == 2 and name not in ok_files:
            seen.add(name)
            out.append(("2", f, f"'{f}' is not allowed at the research root. Only {', '.join(sorted(ok_files))} and the folders "
                                f"{' '.join(sorted(ok_dirs))} (research/README.md); move it into the folder that holds its kind"))
        elif len(parts) > 2 and name not in ok_dirs:
            seen.add(name)
            out.append(("2", f"research/{name}/", f"folder 'research/{name}/' is not in the research layout ({' '.join(sorted(ok_dirs))}); "
                                                  f"move it into one of them or extend research_root_dirs with the owner's approval"))
    return out


def rule3(files: list[str], c: dict) -> list[Viol]:
    out: list[Viol] = []
    ok = set(c["docs_root"])
    for f in files:
        if not f.startswith("docs/"):
            continue
        parts = f.split("/")
        if parts[1] not in ok:
            out.append(("3", f, f"'{f}': docs/ holds only {', '.join(sorted(ok))}; put it under docs/v2/"))
        if f.startswith("docs/v2/research/") and f != "docs/v2/research/README.md":
            out.append(("3", f, f"'{f}': docs/v2/research/ holds only the README.md stub; research lives in research/ (cleanup D11)"))
        if "research" in parts[-1].lower() and not f.startswith("docs/archive/") and f != "docs/v2/research/README.md":
            out.append(("3", f, f"'{f}': no docs file may be named *research*; research lives in research/ (cleanup D11). "
                                f"Rename it, or move it to research/"))
    return out


def rule4(files: list[str], c: dict) -> list[Viol]:
    out: list[Viol] = []
    for f in files:
        if f.startswith("research/types/"):
            head = (ROOT / f).read_text(encoding="utf-8", errors="replace")[:600]
            if GENERATED_HEADER not in head:
                out.append(("4", f, f"'{f}' is not a generated checklist. research/types/ is written only by `node core/bin/capture.ts build` "
                                    f"(no README, no notes); move this file to research/method/ or research/reports/"))
    return out


def rule5(files: list[str], c: dict) -> list[Viol]:
    idx = ROOT / "research/trips/README.md"
    text = idx.read_text(encoding="utf-8") if idx.is_file() else ""
    folders = sorted({f.split("/")[2] for f in files if f.startswith("research/trips/") and f.count("/") >= 3})
    return [("5", fo, f"research/trips/{fo}/ has no row in research/trips/README.md. Add its row (folder, trip id, state) before the first lane file")
            for fo in folders if f"`{fo}`" not in text]


def rule6(files: list[str], c: dict) -> list[Viol]:
    out: list[Viol] = []
    sk = c["skills"]
    fileset = set(files)
    names = {f.split("/")[2] for f in files if f.startswith(".claude/skills/")}
    for n in sorted(names - set(sk)):
        out.append(("6", f".claude/skills/{n}", f".claude/skills/{n}/ is not allowed; the skills are {', '.join(sorted(sk))} (cleanup D18/CLN-7)"))
    for n, limit in sk.items():
        p = f".claude/skills/{n}/SKILL.md"
        if p not in fileset:
            out.append(("6", p, f"{p} is missing; every skill is one SKILL.md"))
            continue
        full = ROOT / p
        if full.is_symlink():
            out.append(("6", p, f"{p} is a symlink; skills are regular files"))
            continue
        text = full.read_text(encoding="utf-8")
        if "research/README.md" not in text:
            out.append(("6", p, f"{p} must link research/README.md (the one map of the research method), not restate it"))
        if len(text.encode()) > limit:
            out.append(("6", p, f"{p} is {len(text.encode())} bytes, over its {limit} byte limit. A skill points at research/README.md; "
                                f"move method text there instead of copying it into the skill"))
    for f in files:
        if f.startswith(".claude/skills/") and (ROOT / f).is_symlink():
            out.append(("6", f, f"'{f}' is a symlink; none is allowed under .claude/skills/"))
    ag = ".claude/agents/travel-researcher.md"
    if ag in fileset and "research/README.md" not in (ROOT / ag).read_text(encoding="utf-8"):
        out.append(("6", ag, f"{ag} must link research/README.md"))
    return out


def rule7(files: list[str], c: dict, hashes: dict[str, str]) -> list[Viol]:
    allow = c["duplicate_allow"]
    by: dict[str, list[str]] = defaultdict(list)
    for f, h in hashes.items():
        if os.path.getsize(ROOT / f) == 0:
            continue
        if f.startswith(("docs/archive/", "research/types/")) or any(fnmatch.fnmatch(f, a) or os.path.basename(f) == a for a in allow["paths"]):
            continue
        by[h].append(f)
    return [("7", "|".join(sorted(ps)), "identical content in " + ", ".join(sorted(ps)) + ". Keep one copy and link to it "
            "(a generated or archive copy is exempt; a font licence pair is allowlisted)")
            for ps in by.values() if len(ps) > 1]


def rule8(files: list[str], c: dict) -> list[Viol]:
    out: list[Viol] = []
    trees = {"docs": [f for f in files if f.startswith("docs/") and not f.startswith("docs/archive/")],
             "research/reports": [f for f in files if f.startswith("research/reports/")]}
    for tree, fl in trees.items():
        imgs = [f for f in fl if Path(f).suffix.lower() in IMAGE_EXT]
        if not imgs:
            continue
        blob = "\n".join((ROOT / f).read_text(encoding="utf-8", errors="replace")
                         for f in fl if Path(f).suffix.lower() in TEXT_EXT)
        for f in imgs:
            if os.path.basename(f) not in blob:
                out.append(("8", f, f"image '{f}' is named by no tracked text file under {tree}/. Link it from the doc it illustrates, or delete it"))
            size = os.path.getsize(ROOT / f)
            if size > MAX_IMAGE:
                out.append(("8", f, f"image '{f}' is {size // 1000} KB, over 1.5 MB. Recompress it, or keep a smaller copy"))
    return out


def rule9(files: list[str], c: dict) -> list[Viol]:
    out: list[Viol] = []
    pat = re.compile(r"\]\(([^)\s]*docs/archive/[^)\s]*)\)")
    for f in files:
        if f.endswith(".md") and not f.startswith(("docs/archive/", "docs/v2/build/handover/memory/")):
            for m in pat.finditer((ROOT / f).read_text(encoding="utf-8", errors="replace")):
                out.append(("9", f"{f} -> {m.group(1)}", f"'{f}' links into docs/archive/ ({m.group(1)}). Nothing live may; copy the idea into a live doc, then link that"))
    return out


# ----- rule 10 --------------------------------------------------------------------------------------------------------------------------
def broken_links_in(f: str, relink) -> list[str]:
    """Relative Markdown links of one file that do not resolve (same reading rules as tools/relink.py check, but over the working tree)."""
    found: list[str] = []
    in_fence: str | None = None
    for line in (ROOT / f).read_text(encoding="utf-8", errors="replace").split("\n"):
        fm = relink.FENCE_RE.match(line)
        if fm:
            marker = fm.group(1)[0]
            in_fence = marker if in_fence is None else (None if in_fence == marker else in_fence)
            continue
        if in_fence:
            continue
        masked, _ = relink._mask_inline_code(line)
        targets = [m.group(3) for m in relink.LINK_RE.finditer(masked)]
        rm = relink.REFDEF_RE.match(masked)
        if rm:
            targets.append(rm.group(3))
        for t in targets:
            if not relink.is_relative_link(t):
                continue
            path, _ = relink._split_target(t)
            if not path:
                continue
            resolved = os.path.normpath(os.path.join(os.path.dirname(f), path))
            if resolved.startswith("..") or not (ROOT / resolved).exists():
                found.append(t)
    return sorted(set(found))


def rule10(files: list[str], c: dict) -> list[Viol]:
    import relink

    fs = set(files)
    dirs: set[str] = set()
    for f in files:
        d = os.path.dirname(f)
        while d and d not in dirs:
            dirs.add(d)
            d = os.path.dirname(d)
    legacy_folders = {f.split("/")[1] for f in files if f.startswith("legacy/") and f.count("/") >= 2}
    out: list[Viol] = []
    for f in files:
        if not (f.startswith(SCAN_PREFIXES) or f in SCAN_FILES) or SKIP_SCAN.search(f) or Path(f).suffix not in SCAN_EXT:
            continue
        if f.startswith("data/") and f.endswith(".json"):
            continue
        text = (ROOT / f).read_text(encoding="utf-8", errors="replace")
        for m in PATH_RE.finditer(text):
            p = m.group(1).rstrip(".")
            nxt = text[m.end():m.end() + 1]
            if any(ch in p for ch in "<*{$") or nxt in "*{<$[":
                continue
            if RUNTIME.search(p) or p in fs or p in dirs or (ROOT / p).exists():
                continue
            parts = p.split("/")
            # C17: legacy/<trip>/<kind>/<name> is a record id, not a path (SKILLS-AND-DATA-ONLY 7, row 25).
            if parts[0] == "legacy" and len(parts) == 4 and parts[1] in legacy_folders and "." not in parts[3]:
                continue
            out.append(("10", f"{f}::{p}", f"'{f}' names '{p}', which does not exist. Fix the path to where the file lives now "
                                           f"(python3 tools/relink.py rewrite handles a scripted move), or delete the mention"))
    for f in files:
        if f.endswith(".md") and (f.startswith(SCAN_PREFIXES) or f in SCAN_FILES) and not SKIP_SCAN.search(f):
            for t in broken_links_in(f, relink):
                out.append(("10", f"{f}::{t}", f"'{f}' has a Markdown link to '{t}' that does not resolve. Fix the link target or remove it"))
    return out


# ----- rule 11 --------------------------------------------------------------------------------------------------------------------------
def freeze_exempt(f: str, c: dict) -> bool:
    return any(fnmatch.fnmatch(f, g) for g in c["legacy_exempt"])


def legacy_current(files: list[str], c: dict) -> dict[str, str]:
    paths = [f for f in files if f.startswith("legacy/") and not freeze_exempt(f, c)]
    return hash_files(paths)


def rule11(files: list[str], c: dict) -> tuple[list[Viol], dict[str, str], dict]:
    pins_doc = json.loads(PINS.read_text(encoding="utf-8")) if PINS.is_file() else {"pins": {}, "raised": []}
    pins = pins_doc["pins"]
    cur = legacy_current(files, c)
    out: list[Viol] = []
    for f, h in sorted(cur.items()):
        if f not in pins:
            out.append(("11", f, f"'{f}' is a new file under legacy/. {FREEZE_MSG}. Put it in web/, or in data/ if it is data"))
        elif pins[f] != h:
            out.append(("11", f, f"'{f}' changed. {FREEZE_MSG}. Revert it; if the change is a data move or the owner approved it, run "
                                 f"`python3 tools/tree_check.py --write --reason \"<why>\"`"))
    return out, cur, pins_doc


def write_pins(files: list[str], c: dict, reason: str | None) -> int:
    viol, cur, doc = rule11(files, c)
    removed = sorted(set(doc["pins"]) - set(cur))
    if not viol and not removed:
        print("legacy pins already match; nothing to write")
        return 0
    if viol and not (reason and reason.strip()):
        print("refusing to refresh the legacy pins without --reason \"<why>\" (it is appended to the 'raised' log):", file=sys.stderr)
        for _, _, m in viol:
            print("  " + m, file=sys.stderr)
        return 1
    touched = sorted(v[1] for v in viol)
    doc["pins"] = dict(sorted(cur.items()))
    if viol:
        doc.setdefault("raised", []).append(f"{date.today().isoformat()} {reason.strip()} ({len(touched)} file(s): {', '.join(touched)})")
    if removed:
        doc.setdefault("raised", []).append(f"{date.today().isoformat()} files left legacy/ ({len(removed)}): {', '.join(removed)}")
    PINS.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {PINS.relative_to(ROOT)}: {len(cur)} pins, {len(touched)} refreshed, {len(removed)} removed")
    return 0


# ----- driver ---------------------------------------------------------------------------------------------------------------------------
def all_violations(files: list[str], c: dict) -> list[Viol]:
    dup_paths = [f for f in files if f.startswith(("docs/", "research/"))]
    out: list[Viol] = []
    for r in (rule1, rule2, rule3, rule4, rule5, rule6, rule8, rule9, rule10):
        out += r(files, c)
    out += rule7(files, c, hash_files(dup_paths))
    out += rule11(files, c)[0]
    return out


def baseline_keys(c: dict) -> dict[tuple[str, str], str]:
    return {(rule, e["key"]): e["reason"] for rule, entries in c.get("baseline", {}).items() for e in entries}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="default")
    ap.add_argument("--list", action="store_true", help="print every violation, baselined or not")
    ap.add_argument("--write", action="store_true", help="refresh the legacy pins (needs --reason)")
    ap.add_argument("--reason", help="why the pins change; appended to the 'raised' log")
    args = ap.parse_args(argv)

    c = load_contract()
    files = listed()
    if args.write:
        return write_pins(files, c, args.reason)
    viol = all_violations(files, c)
    base = baseline_keys(c)
    if args.list:
        for r, k, m in sorted(viol):
            print(f"rule {r} {'[baselined] ' if (r, k) in base else ''}{k}")
        return 0
    bad = [v for v in viol if (v[0], v[1]) not in base]
    stale = sorted(set(base) - {(v[0], v[1]) for v in viol})
    if stale:
        print("baseline entries that no longer fire (remove them from tools/tree_contract.json):\n  " + "\n  ".join(f"rule {r} {k}" for r, k in stale))
    if bad:
        print("folder contract broken (tools/tree_check.py, docs/v2/CLEANUP-PLAN.md CLN-5):", file=sys.stderr)
        for r, _, m in sorted(bad):
            print(f"  [rule {r}] {m}", file=sys.stderr)
        return 1
    print(f"folder contract OK: 11 rules, {len(files)} files, {len(viol)} baselined exception(s), {len(load_pins())} legacy files pinned")
    return 0


def load_pins() -> dict:
    return json.loads(PINS.read_text(encoding="utf-8"))["pins"] if PINS.is_file() else {}


if __name__ == "__main__":
    sys.exit(main())
